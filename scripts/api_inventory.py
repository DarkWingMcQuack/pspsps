#!/usr/bin/env python3
"""Generate a textual API reference. This is NOT a Scala parser or ABI checker.

Usage: python3 scripts/api_inventory.py [--check]
Only the Python standard library is required (Python 3.10+).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ("core", "effect", "fs2", "all")
REFERENCE = ROOT / "docs" / "reference.md"
INVENTORY = ROOT / "docs" / "api-inventory.json"


def collect() -> list[dict[str, object]]:
    """Extract this project's consistently shaped extension declarations."""
    entries: list[dict[str, object]] = []
    for module in MODULES:
        for source in sorted((ROOT / "modules" / module / "src/main/scala-3").rglob("*.scala")):
            lines = source.read_text(encoding="utf-8").splitlines()
            extension = ""
            for index, line in enumerate(lines):
                if line.startswith("  extension "):
                    extension = line.strip()
                match = re.match(r"    def (as\w+|nullable)\b", line)
                if not match:
                    continue
                if not extension:
                    raise ValueError(f"Method without a receiver: {source}:{index + 1}")
                signature_lines = [line.strip()]
                end = index
                while not re.search(r"\s=(?:\s|$)", " ".join(signature_lines)):
                    end += 1
                    if end >= len(lines):
                        raise ValueError(f"Unterminated signature: {source}:{index + 1}")
                    signature_lines.append(lines[end].strip())
                signature = re.split(r"\s=(?:\s|$)", " ".join(signature_lines), maxsplit=1)[0]
                signature = re.sub(r"\(\s+", "(", signature)
                signature = re.sub(r"\s+\)", ")", signature)
                entries.append({
                    "module": module,
                    "family": source.stem.removesuffix("Syntax"),
                    "name": match.group(1),
                    "receiver": extension,
                    "signature": signature,
                    "source": str(source.relative_to(ROOT)),
                    "line": index + 1,
                })
    return entries


def render_reference(entries: list[dict[str, object]]) -> str:
    names = {entry["name"] for entry in entries}
    lines = [
        "# API reference",
        "",
        "Generated by `python3 scripts/api_inventory.py`. Do not edit by hand.",
        "",
        f"{len(entries)} extension declarations, {len(names)} distinct method names.",
        "",
        "Signatures below omit bodies. This source-text inventory is not a compiler",
        "ABI report and does not establish that the signatures typecheck. The return",
        "types and typeclass constraints are intentionally visible for API review.",
        "",
        "Use `import pspsps.syntax.common.*` for everyday constructors; `all.*` includes",
        "every family. For Scala 2.13 imports, replace `*` with `_`. Choose the",
        "focused import shown for each family. Lowercase family objects are all",
        "in `pspsps.syntax`. `core.*`, `effect.*`, and `streaming.*` collect a module.",
        "",
        "**Semantics:** `asResourceEval` evaluates an effect without registering cleanup; `asStreamEmit` emits",
        "one value, including a collection; `asStreamEmits` emits sequence elements.",
        "`asPullPure` yields a terminal result, while `asPullOutput1` emits output.",
        "Explicit `Wrap` names disambiguate nested shapes.",
        "",
    ]
    family_imports = {
        "OptionT": "optionT", "EitherT": "eitherT", "IorT": "iorT",
        "WriterT": "writerT", "Kleisli": "kleisli", "StateT": "stateT",
        "Nullable": "nullable", "Resource": "resource", "Ref": "ref",
        "Conditional": "conditional",
        "Stream": "stream", "Pull": "pull", "Chunk": "chunk",
    }
    previous_module = None
    previous_source = None
    previous_receiver = None
    open_fence = False
    for entry in entries:
        module, source = entry["module"], entry["source"]
        if source != previous_source:
            if open_fence:
                lines += ["```", ""]
                open_fence = False
            if module != previous_module:
                lines += [f"## {str(module).capitalize()} module", ""]
            family = str(entry["family"])
            lines += [
                f"### {family}", "",
                f"`import pspsps.syntax.{family_imports[family]}.*`", "",
                f"[Implementation](../{source})", "",
                "```scala",
            ]
            open_fence = True
            previous_receiver = None
        if entry["receiver"] != previous_receiver:
            if previous_receiver is not None:
                lines.append("")
            lines.append(str(entry["receiver"]))
        lines.append("  " + str(entry["signature"]))
        previous_receiver = entry["receiver"]
        previous_source, previous_module = source, module
    if open_fence:
        lines += ["```", ""]
    lines += [
        "## Conditional builders", "",
        "`pspsps.builders.{Either, Option, EitherT, OptionT}` provide staged",
        "conditional factories. Their methods are documented separately in",
        "[conditional builders](conditionals.md); the inventory above counts only",
        "extension methods, not builder methods or typeclass members.", "",
        "## Companion tooling", "",
        "The `pspsps-laws` module additionally exposes `ConstructorLaws[F]` and",
        "`pspsps.laws.discipline.ConstructorTests[F]` for transformer constructor",
        "coherence. It is separate from runtime syntax dependencies.", "",
        "See [design notes](design.md), [verification status](../VERIFICATION.md),",
        "and [executable documentation](src/main/mdoc/index.md).", "",
    ]
    return "\n".join(lines)


def generated_files() -> dict[Path, str]:
    entries = collect()
    payload = {"schema_version": 1, "declaration_count": len(entries),
               "distinct_name_count": len({e["name"] for e in entries}),
               "extensions": entries}
    return {REFERENCE: render_reference(entries),
            INVENTORY: json.dumps(payload, indent=2, ensure_ascii=False) + "\n"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on missing or stale generated files")
    args = parser.parse_args()
    stale = []
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated files: " + ", ".join(stale), file=sys.stderr)
        print("Run python3 scripts/api_inventory.py", file=sys.stderr)
        return 1
    if args.check:
        print("API inventory matches source text (not a compilation check).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
